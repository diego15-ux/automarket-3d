/*
 * Ayudas para funciones del navegador que solo existen en páginas seguras (https o localhost).
 * Por la red local (http://192.168.x.x:3000) el teléfono no trae crypto.randomUUID,
 * crypto.subtle ni navigator.clipboard; aquí cada una tiene un plan B que sí funciona.
 */

/** Id aleatorio con forma de UUID v4. */
export function randomId(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;
  const hex = [...bytes].map(byte => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/** Copia texto. Sin navigator.clipboard usa un textarea oculto y execCommand. */
export async function copyText(text: string): Promise<void> {
  if (navigator.clipboard?.writeText && window.isSecureContext) {
    await navigator.clipboard.writeText(text);
    return;
  }
  const area = document.createElement('textarea');
  area.value = text;
  area.setAttribute('readonly', '');
  area.style.position = 'fixed';
  area.style.top = '0';
  area.style.opacity = '0';
  document.body.append(area);
  area.select();
  area.setSelectionRange(0, text.length);
  const copied = document.execCommand('copy');
  area.remove();
  if (!copied) throw new Error('El navegador no dejó copiar.');
}

